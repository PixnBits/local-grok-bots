package permission

import (
	"encoding/json"
	"path/filepath"
	"sort"
	"strings"

	"github.com/PixnBits/local-grok-bots/internal/clisession"
)

// NativeRule is one accepted durable pattern written for a CLI the user
// runs outside the bot. The isolated bot turn does not load these as
// --allowedTools: the broker still decides, so the audit record exists.
type NativeRule struct {
	Effect  string
	Pattern string
}

// WriteNativeRules writes the Claude settings fragment and the Grok
// allow/deny lines for rules. Ask rules are recorded as lgbAsk because
// Claude and Grok have no ask flag; the broker enforces them.
// The directory is created with a no-follow walk. A symlink parent or a
// symlink at either file name is refused and not followed.
func WriteNativeRules(dir string, rules []NativeRule) error {
	if strings.TrimSpace(dir) == "" {
		return nil
	}
	abs, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	allow, deny, ask := splitNative(rules)
	doc := map[string]any{
		"permissions": map[string]any{
			"allow": allow,
			"deny":  deny,
		},
		"lgbAsk": ask,
	}
	body, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return err
	}
	body = append(body, '\n')
	if err := clisession.WriteFileInDir(abs, "user-permissions.json", body, 0o600); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Generated by local-grok-bots. Not loaded into the isolated bot turn.\n")
	b.WriteString("# The broker enforces these while the permission host is attached.\n")
	b.WriteString("# Pass allow and deny lines as grok --allow / --deny when running grok directly.\n")
	for _, p := range allow {
		b.WriteString("allow ")
		b.WriteString(p)
		b.WriteByte('\n')
	}
	for _, p := range deny {
		b.WriteString("deny ")
		b.WriteString(p)
		b.WriteByte('\n')
	}
	for _, p := range ask {
		b.WriteString("# ask ")
		b.WriteString(p)
		b.WriteString("  (broker only)\n")
	}
	return clisession.WriteFileInDir(abs, "grok-permission-rules", []byte(b.String()), 0o600)
}

func splitNative(rules []NativeRule) (allow, deny, ask []string) {
	allow, deny, ask = []string{}, []string{}, []string{}
	for _, r := range rules {
		p := strings.TrimSpace(r.Pattern)
		if p == "" {
			continue
		}
		switch strings.ToLower(strings.TrimSpace(r.Effect)) {
		case "allow":
			allow = append(allow, p)
		case "deny":
			deny = append(deny, p)
		case "ask":
			ask = append(ask, p)
		}
	}
	sort.Strings(allow)
	sort.Strings(deny)
	sort.Strings(ask)
	return allow, deny, ask
}
